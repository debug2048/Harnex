// In dev mode, log every distinct missing key exactly once so coverage gaps are obvious
// during development without spamming the console on a hot template re-render.
const _missingKeyWarned: Set<string> = new Set()

/**
 * Reactive translator. Use in templates: `{{ t('sidebar.newChat') }}`.
 * Optional `vars` substitutes `{name}` placeholders inside the message.
 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const localeMsgs = messages[localeRef.value]
  let raw = localeMsgs?.[key]
  if (raw == null) {
    raw = messages['en']?.[key]
    if (raw == null) {
      // Dev-only warning: production bundles strip import.meta.env.DEV.
      if (import.meta.env.DEV && !_missingKeyWarned.has(key)) {
        _missingKeyWarned.add(key)
        // eslint-disable-next-line no-console
        console.warn('[i18n] missing key:', key)
      }
      raw = key
    }
  }
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`))
}

export function setLocale(l: Locale) {
  localeRef.value = l
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, l)
  } catch { /* the in-memory locale remains active */ }
  if (typeof document !== 'undefined') document.documentElement.setAttribute('lang', l)
}

/** For places that need to read the current locale reactively (e.g. v-model on a select). */
export const locale = computed({
  get: () => localeRef.value,
  set: (v: Locale) => setLocale(v),
})

// Apply the lang attribute on first load too.
if (typeof document !== 'undefined') document.documentElement.setAttribute('lang', localeRef.value)
