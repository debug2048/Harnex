// Tiny dependency-free i18n. Compiles to ~1 KB; no vue-i18n needed for the fixed
// chrome strings we want to localise. Usage:
//   import { t, setLocale, useLocale } from './i18n'
//   t('sidebar.newChat')                  // → "新对话" or "New chat"
//   t('settings.rescanFound', { n: 3 })   // → "已扫描到 3 个技能" / "Found 3 skills"
//   setLocale('en')                       // persists to localStorage and re-renders via the reactive locale ref
//
// Adding a new string: drop the same key into both messages tables. Missing keys
// fall through to the en table, then to the key itself, so partial coverage is safe.

import { ref, computed } from 'vue'

export type Locale = 'zh-CN' | 'en'

const STORAGE_KEY = 'harnex_locale'

function detectInitialLocale(): Locale {
  let saved: Locale | null = null
  try {
    saved = typeof localStorage === 'undefined'
      ? null
      : localStorage.getItem(STORAGE_KEY) as Locale | null
  } catch {
    // Embedded/private contexts may deny storage; language detection still works.
  }
  if (saved === 'zh-CN' || saved === 'en') return saved
  // Default: zh-CN if browser is Chinese, else English.
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('zh')
    ? 'zh-CN'
    : 'en'
}

